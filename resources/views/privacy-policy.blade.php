    <h1>Política de Privacidade</h1>
    <p class="updated">Última atualização: 4 de setembro de 2026</p>
    <p>Esta política explica como a TeresinaSoft trata dados pessoais utilizados pelo serviço de integração de agendamentos, mensagens e serviços fiscais.</p>

    <h2>1. Dados tratados</h2>
    <p>Podemos tratar nome, telefone, identificadores de agendamento, conteúdo e status de mensagens, dados do tomador necessários à emissão fiscal e registros técnicos de operação. O serviço não solicita senhas de WhatsApp, tokens ou certificados por mensagens.</p>

    <h2>2. Finalidade</h2>
    <p>Os dados são utilizados para enviar notificações solicitadas pelo estabelecimento, acompanhar a entrega das mensagens, processar solicitações de NFS-e, prevenir duplicidades, atender obrigações legais e manter a segurança e auditoria do serviço.</p>

    <h2>3. Compartilhamento</h2>
    <p>Quando necessário para a finalidade solicitada, os dados podem ser transmitidos à Meta Platforms (WhatsApp Business) e ao provedor fiscal configurado pelo estabelecimento. Não vendemos dados pessoais.</p>

    <h2>4. Retenção e segurança</h2>
    <p>Conservamos os dados pelo período necessário às finalidades acima, às obrigações legais e à resolução de disputas. Aplicamos controle de acesso, HTTPS, autenticação entre sistemas, registros de auditoria e minimização de dados. Nenhum método de transmissão ou armazenamento é absolutamente seguro.</p>

    <h2>5. Direitos do titular</h2>
    <p>O titular pode solicitar confirmação de tratamento, acesso, correção, eliminação quando aplicável e informações sobre compartilhamento, observadas as obrigações legais. Solicitações devem ser encaminhadas ao responsável pelo estabelecimento que utilizou o serviço.</p>

    <h2>6. Cookies e contato</h2>
    <p>As páginas públicas utilizam apenas o necessário para funcionamento e não exigem cadastro. Para dúvidas sobre esta política, entre em contato pelo e-mail <a href="mailto:italo@teresinasoft.com.br">italo@teresinasoft.com.br</a>.</p>

